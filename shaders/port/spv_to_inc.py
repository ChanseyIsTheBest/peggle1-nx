#!/usr/bin/env python3
"""Writes SPIR-V modules as C++ arrays of 32-bit words (little-endian words, as the file stores them).

  python spv_to_inc.py <out.inc> <name>=<module.spv> [...]
"""
import struct
import sys


def main():
    out, pairs = sys.argv[1], sys.argv[2:]
    lines = ['// Generated by shaders/port/build_port_shaders.sh from shaders/port/*.hlsl (the port\'s own shaders). Do not edit.',
             '// clang-format off']
    for pair in pairs:
        name, path = pair.split('=', 1)
        data = open(path, 'rb').read()
        if len(data) % 4 or struct.unpack_from('<I', data, 0)[0] != 0x07230203:
            sys.exit(f'{path}: not a SPIR-V module')
        words = struct.unpack(f'<{len(data) // 4}I', data)
        lines.append(f'constexpr uint32_t {name}[] = {{')
        for i in range(0, len(words), 8):
            lines.append('    ' + ', '.join(f'0x{w:08X}u' for w in words[i:i + 8]) + ',')
        lines.append('};')
    lines.append('// clang-format on')
    open(out, 'w', newline='\n').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
